#!/usr/bin/env python3
"""Study 019 contract de-formalization -- DESIGN DRAFT, NOT REGISTERED.

BRIEF.md section 3: arm B's prose contract is "produced by a registered mechanical
de-formalization of C's JSON Schema (same field/value inventory, machine-checkable structure
stripped), own digest". This script IS that de-formalization: it reads
RESULT-CONTRACT.schema.json and writes generated/ARM-B-CONTRACT.md.

The rule, stated so a reviewer can check it against the output:

  1. Every member of the schema's `properties` becomes one prose bullet naming the member,
     its JSON type, and whether it is required.
  2. Every `enum` becomes the same closed list of values, in schema order, in prose.
  3. Every `if/then` in `allOf` becomes one prose sentence built from its `description`
     (the descriptions are written to be the sentences).
  4. `additionalProperties: false` becomes one sentence forbidding other members.
  5. Nothing machine-checkable survives: no schema keywords, no `$id`, no types spelled as
     JSON Schema, no fenced schema, no file to validate against.
  6. Nothing is added that is not in the schema. The two arms therefore carry the same field
     and value inventory and differ in the FORMALITY of the statement.

Usage: python3 deformalize_contract.py
"""

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMA = os.path.join(HERE, "RESULT-CONTRACT.schema.json")
OUT = os.path.join(HERE, "generated", "ARM-B-CONTRACT.md")

HEADER = """<!--
GENERATED by deformalize_contract.py from RESULT-CONTRACT.schema.json. Do not hand-edit.
DESIGN DRAFT, NOT REGISTERED.
-->

## The result your decision rule must produce

Stated as a description, not as a schema. Nothing here is machine-checked for you.
"""

TYPE_WORDS = {
    "object": "an object",
    "string": "a string",
    "array": "a list",
    "number": "a number",
    "boolean": "true or false",
}


def quoted_list(values):
    return ", ".join("`%s`" % v for v in values)


def main():
    with open(SCHEMA) as fh:
        schema = json.load(fh)

    lines = [HEADER]
    lines.append("The decision entrypoint's value is %s. %s\n"
                 % (TYPE_WORDS[schema["type"]], schema["description"].split(". ")[0] + "."))

    required = set(schema.get("required", []))
    lines.append("It carries these members:\n")
    for name, prop in schema["properties"].items():
        req = "required" if name in required else "optional"
        bits = ["`%s` (%s, %s)" % (name, TYPE_WORDS.get(prop.get("type"), prop.get("type")), req)]
        desc = prop.get("description")
        if desc:
            bits.append("— " + desc)
        lines.append("- " + " ".join(bits))
        if "enum" in prop:
            lines.append("  Its only permitted values are: %s. No other value is allowed."
                         % quoted_list(prop["enum"]))
        items = prop.get("items")
        if items and "enum" in items:
            lines.append("  Each entry is one of: %s. No other value is allowed."
                         % quoted_list(items["enum"]))
        if prop.get("uniqueItems"):
            lines.append("  A value may not appear twice in the list.")
    lines.append("")

    if schema.get("additionalProperties") is False:
        lines.append("The result carries no members other than the ones named above.\n")

    conds = [c for c in schema.get("allOf", []) if "description" in c]
    if conds:
        lines.append("Two further conditions hold:\n")
        for c in conds:
            lines.append("- " + c["description"])
        lines.append("")

    text = "\n".join(lines)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(text)

    for label, path in (("schema", SCHEMA), ("prose contract", OUT)):
        with open(path, "rb") as fh:
            print("%-15s sha256=%s  %d bytes" % (label, hashlib.sha256(fh.read()).hexdigest()[:16],
                                                 os.path.getsize(path)))
    return 0


if __name__ == "__main__":
    sys.exit(main())

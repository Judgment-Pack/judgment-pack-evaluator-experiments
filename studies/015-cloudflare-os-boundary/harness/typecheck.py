"""The fixture typecheck — every ledger record held to the pinned contract types.

The platform ships no runtime validation for its own action records; the contract is
TypeScript types. This gate holds every frozen `ledger.json` entry to the pinned
**published contract layer** — `ActionLogEntry` (with `ActionDescription`,
`ObservationDescription`, `HookDescription`, `AiChatAuthorInfo`, `ActionKind`,
`WorkpieceId`) from `packages/workshop-shared/src/api.ts` and `gatekeeper.ts` — using
the clone's own TypeScript compiler at the lockfile-resolved version. A fixture that
fails is pipeline-invalid (PREREGISTRATION section 6), never a detection.

Scope, stated honestly: the retained ledger records carry two server-only members the
published log does not (`action`, the gatekeeper's opaque key, and `caller`), mirroring
the server-side `ActionRecord` (overseer.ts:424); the generator strips exactly those two
before the `satisfies` check. Holding fixtures to the server type itself was attempted
and is not reproducible from the committed tree: the backend graph only typechecks
against a wrangler-regenerated `worker-configuration.d.ts` (Env bindings, text-module
declarations, Uint8Array codec types), so the committed snapshot cannot standalone-check
its own backend — recorded as an apparatus finding. Auto-approval rules are held to the
same shared types member-by-member (`ActionKind`, `AiChatAuthorInfo`, `WorkpieceId`),
mirroring `AutoApproveTagRecord` (overseer.ts:489).

Mechanics: the fixture bytes are rendered as typed literals (`satisfies`) into a
generated file in a temporary directory, with a transient tsconfig whose paths point
into the pinned clone; nothing is written into the clone and nothing generated is
frozen. Run: CFOS_SOURCE=... python harness/typecheck.py
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

STUDY = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(STUDY / "harness"))

import cf_runner  # noqa: E402


def _literal(value, indent=0):
    """Render a fixture JSON value as a TypeScript literal, reviving date strings."""
    pad = "  " * indent
    inner = "  " * (indent + 1)
    if isinstance(value, dict):
        members = []
        for key, member in value.items():
            rendered = (
                'new Date("%s")' % member
                if key in ("createdAt", "appliedAt") and isinstance(member, str)
                else _literal(member, indent + 1)
            )
            members.append('%s"%s": %s' % (inner, key, rendered))
        return "{\n" + ",\n".join(members) + "\n" + pad + "}"
    if isinstance(value, list):
        return "[" + ", ".join(_literal(item, indent) for item in value) + "]"
    return json.dumps(value)


def generated_source(cells):
    """cells: iterable of (cell_id, ledger entries, auto rules)."""
    lines = [
        "// Generated by harness/typecheck.py from frozen fixture bytes; transient.",
        'import type { ActionLogEntry, AiChatAuthorInfo, WorkpieceId } from "@shared/api.js";',
        'import type { ActionKind } from "@shared/gatekeeper.js";',
        "",
        "// Structural twin of the server-side AutoApproveTagRecord (overseer.ts:489),",
        "// assembled from the shared types its members are declared with.",
        "type AutoApproveRule = {",
        "  gatekeeperId: WorkpieceId;",
        "  actionKind: ActionKind;",
        "  enabledBy: AiChatAuthorInfo;",
        "};",
        "",
    ]
    for cell_id, ledger, rules in cells:
        safe = cell_id.replace("-", "_")
        for index, entry in enumerate(ledger):
            published = {
                key: value
                for key, value in entry.items()
                if key not in ("action", "caller")
            }
            lines.append(
                "const %s_ledger_%d = %s satisfies ActionLogEntry;"
                % (safe, index, _literal(published))
            )
        for index, rule in enumerate(rules):
            lines.append(
                "const %s_rule_%d = %s satisfies AutoApproveRule;"
                % (safe, index, _literal(rule))
            )
    lines.append("")
    lines.append("export {};")
    return "\n".join(lines) + "\n"


def fixture_cells():
    roots = [STUDY / "fixtures" / "baseline"]
    mutations = STUDY / "fixtures" / "mutations"
    if mutations.is_dir():
        roots.extend(sorted(path for path in mutations.iterdir() if path.is_dir()))
    for root in roots:
        ledger_path = root / "ledger.json"
        platform_path = root / "platform.json"
        if not ledger_path.is_file() or not platform_path.is_file():
            continue
        ledger = json.loads(ledger_path.read_text(encoding="utf-8"))
        platform = json.loads(platform_path.read_text(encoding="utf-8"))
        cell_id = "pos-baseline" if root.name == "baseline" else root.name
        yield cell_id, ledger, platform.get("autoApproveTags") or []


def typecheck_problems():
    source = cf_runner.source_root()
    tsc = (
        source
        / "node_modules"
        / ".pnpm"
        / "typescript@5.9.3"
        / "node_modules"
        / "typescript"
        / "bin"
        / "tsc"
    )
    if not tsc.is_file():
        return ["the pinned clone's typescript compiler is not installed"]
    with tempfile.TemporaryDirectory(prefix="study015-typecheck-") as scratch:
        scratch = Path(scratch)
        (scratch / "fixtures.gen.ts").write_text(
            generated_source(fixture_cells()), encoding="utf-8"
        )
        shared = source / "packages" / "workshop-shared" / "src"
        stub = STUDY / "probes" / "stubs" / "cloudflare-workers.ts"
        # The same ambient types workshop-shared's own tsconfig loads
        # ("@cloudflare/workers-types/experimental"), by file path because this
        # transient tsconfig lives outside the clone's node_modules chain.
        workers_types = (
            source / "packages" / "workshop-shared" / "node_modules" / "@cloudflare"
            / "workers-types" / "experimental" / "index.d.ts"
        )
        tsconfig = {
            "compilerOptions": {
                "target": "ES2022",
                "lib": ["esnext"],
                "module": "ESNext",
                "moduleResolution": "bundler",
                "strict": True,
                "noEmit": True,
                "skipLibCheck": True,
                "types": [str(workers_types)],
                "baseUrl": ".",
                "paths": {
                    "@shared/*": [str(shared) + "/*"],
                    "cloudflare:workers": [str(stub)],
                },
            },
            "files": ["fixtures.gen.ts"],
        }
        (scratch / "tsconfig.json").write_text(
            json.dumps(tsconfig, indent=2), encoding="utf-8"
        )
        completed = subprocess.run(
            ["node", str(tsc), "-p", str(scratch)],
            capture_output=True,
            timeout=600,
        )
        if completed.returncode == 0:
            return []
        output = completed.stdout.decode("utf-8", "replace")
        return [
            line
            for line in output.splitlines()
            if line.strip() and "error TS" in line
        ] or ["tsc failed: " + output[-1000:]]


def main():
    problems = typecheck_problems()
    for problem in problems:
        print(problem)
    print("fixture typecheck:", "clean" if not problems else "%d problems" % len(problems))
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())

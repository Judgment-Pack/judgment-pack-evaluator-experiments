"""The fixture typecheck — every retained record held to the pinned server-side types.

The platform performs no offline validation of a retained or exported action record, so
this gate supplies the only mechanical fidelity check the study has: every frozen
`ledger.json` entry is held to `ActionRecord` and every auto-approval rule to
`AutoApproveTagRecord` — the **server-side** types at
`packages/workshop-backend/src/overseer.ts` — by the pinned clone's own TypeScript
compiler, under the backend package's own tsconfig. A fixture that fails is
pipeline-invalid (PREREGISTRATION section 6), never a detection.

An earlier draft recorded a finding that binding to the server-side type was "not
reproducible from the committed tree" because the backend needs a wrangler-regenerated
`worker-configuration.d.ts`. **That finding was wrong and is withdrawn** (DEVIATIONS.md):
the file is tracked at the pin, and the backend program typechecks green once the one
committed codegen step below has run. The gate binds the real server type accordingly,
and no field is stripped to make it pass.

Mechanics: `packages/workshop-backend/scripts/build-format-blueprints.mjs` runs first
(idempotent; it writes one git-ignored file under the clone's `src/generated/`, so the
clone's *tracked* tree stays clean and the apparatus self-report still verifies). The
fixture bytes are then rendered as typed literals (`satisfies`) into a generated file in
a temporary directory, compiled under a transient tsconfig that `extends` the backend
package's own — inheriting its lib, strictness and path mapping, with `types` re-anchored
absolutely because TypeScript resolves an inherited relative type entry against the
extending file. Nothing generated is frozen and nothing is written into the clone's
tracked tree.

Run: CFOS_SOURCE=... python harness/typecheck.py
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

STUDY = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(STUDY / "harness"))

import cf_runner  # noqa: E402

TYPESCRIPT_VERSION = "5.9.3"


def _literal(value, indent=0):
    """Render a fixture JSON value as a TypeScript literal, reviving date strings."""
    pad = "  " * indent
    inner = "  " * (indent + 1)
    if isinstance(value, dict):
        members = []
        for key, member in value.items():
            rendered = (
                'new Date("%s")' % member
                if key in ("createdAt", "appliedAt") and isinstance(member, str)
                else _literal(member, indent + 1)
            )
            members.append('%s"%s": %s' % (inner, key, rendered))
        return "{\n" + ",\n".join(members) + "\n" + pad + "}"
    if isinstance(value, list):
        return "[" + ", ".join(_literal(item, indent) for item in value) + "]"
    return json.dumps(value)


def generated_source(cells, overseer_module):
    """cells: iterable of (cell_id, ledger entries, auto rules)."""
    lines = [
        "// Generated by harness/typecheck.py from frozen fixture bytes; transient.",
        'import type { ActionRecord, AutoApproveTagRecord } from "%s";' % overseer_module,
        "",
    ]
    for cell_id, ledger, rules in cells:
        safe = cell_id.replace("-", "_")
        for index, entry in enumerate(ledger):
            lines.append(
                "const %s_ledger_%d = %s satisfies ActionRecord;"
                % (safe, index, _literal(entry))
            )
        for index, rule in enumerate(rules):
            lines.append(
                "const %s_rule_%d = %s satisfies AutoApproveTagRecord;"
                % (safe, index, _literal(rule))
            )
    lines.append("")
    lines.append("export {};")
    return "\n".join(lines) + "\n"


def fixture_cells():
    """Every constructed cell in both strata, locked first."""
    roots = [STUDY / "fixtures" / "baseline"]
    for parent in ("mutations", "holdout"):
        directory = STUDY / "fixtures" / parent
        if directory.is_dir():
            roots.extend(sorted(path for path in directory.iterdir() if path.is_dir()))
    for root in roots:
        ledger_path = root / "ledger.json"
        platform_path = root / "platform.json"
        if not ledger_path.is_file() or not platform_path.is_file():
            continue
        ledger = json.loads(ledger_path.read_text(encoding="utf-8"))
        platform = json.loads(platform_path.read_text(encoding="utf-8"))
        cell_id = "pos-baseline" if root.name == "baseline" else root.name
        yield cell_id, ledger, platform.get("autoApproveTags") or []


def tsc_path(source):
    return (
        source
        / "node_modules"
        / ".pnpm"
        / ("typescript@" + TYPESCRIPT_VERSION)
        / "node_modules"
        / "typescript"
        / "bin"
        / "tsc"
    )


def _codegen_problems(source):
    """The one committed codegen step the backend program needs. Idempotent."""
    backend = source / "packages" / "workshop-backend"
    script = backend / "scripts" / "build-format-blueprints.mjs"
    if not script.is_file():
        return ["the backend's committed codegen script is absent: %s" % script]
    completed = subprocess.run(
        ["node", str(script)], cwd=str(backend), capture_output=True, timeout=600
    )
    if completed.returncode != 0:
        return [
            "the backend codegen step failed: "
            + completed.stderr.decode("utf-8", "replace")[-600:]
        ]
    return []


def typecheck_problems():
    source = cf_runner.source_root()
    tsc = tsc_path(source)
    if not tsc.is_file():
        return ["the pinned clone's typescript compiler is not installed"]
    problems = _codegen_problems(source)
    if problems:
        return problems
    backend = source / "packages" / "workshop-backend"
    overseer = backend / "src" / "overseer.js"
    with tempfile.TemporaryDirectory(prefix="study015-typecheck-") as scratch:
        scratch = Path(scratch)
        generated = scratch / "fixtures.gen.ts"
        generated.write_text(
            generated_source(fixture_cells(), str(overseer)), encoding="utf-8"
        )
        tsconfig = {
            "extends": str(backend / "tsconfig.json"),
            "compilerOptions": {
                "noEmit": True,
                "declaration": False,
                "declarationMap": False,
                "sourceMap": False,
                # Re-anchored absolutely: an inherited relative `types` entry resolves
                # against the extending file, not the base config.
                "types": [str(backend / "worker-configuration.d.ts")],
            },
            "files": [str(generated)],
        }
        (scratch / "tsconfig.json").write_text(
            json.dumps(tsconfig, indent=2), encoding="utf-8"
        )
        completed = subprocess.run(
            ["node", str(tsc), "-p", str(scratch / "tsconfig.json")],
            capture_output=True,
            timeout=900,
        )
        if completed.returncode == 0:
            return []
        output = completed.stdout.decode("utf-8", "replace")
        return [
            line for line in output.splitlines() if line.strip() and "error TS" in line
        ] or ["tsc failed: " + output[-1000:]]


def main():
    problems = typecheck_problems()
    for problem in problems:
        print(problem)
    print(
        "fixture typecheck:", "clean" if not problems else "%d problems" % len(problems)
    )
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
